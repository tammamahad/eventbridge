function unique(list) {
  return Array.from(new Set((list || []).filter(Boolean)));
}

function hashCode(input) {
  let hash = 0;
  for (let i = 0; i < input.length; i += 1) {
    hash = (hash << 5) - hash + input.charCodeAt(i);
    hash |= 0;
  }
  return Math.abs(hash);
}

function rotate(list, index) {
  if (!Array.isArray(list) || list.length === 0) return [];
  const normalized = index % list.length;
  return [...list.slice(normalized), ...list.slice(0, normalized)];
}

function primaryImageForVendor(vendor) {
  const businessName = String(vendor?.businessName || "");
  const category = String(vendor?.category || "");
  return VENDOR_PRIMARY_IMAGES[businessName] || (CATEGORY_IMAGE_POOLS[category] || CATEGORY_IMAGE_POOLS.default)[0];
}

function portfolioPoolForVendor(vendor) {
  const category = String(vendor?.category || "");
  const businessName = String(vendor?.businessName || "event-vendor");
  const primary = primaryImageForVendor(vendor);
  const pool = unique([
    ...(CATEGORY_IMAGE_POOLS[category] || CATEGORY_IMAGE_POOLS.default),
    ...CATEGORY_IMAGE_POOLS.default,
  ]).filter((url) => url !== primary);

  return rotate(pool, hashCode(`${businessName}-portfolio-${category}`));
}

export function getVendorImageUrl(vendor) {
  return primaryImageForVendor(vendor);
}

export function getVendorImageCandidates(vendor, count = 8) {
  const primary = primaryImageForVendor(vendor);
  const pool = portfolioPoolForVendor(vendor);
  return [primary, ...pool].slice(0, Math.max(1, count));
}

export function getVendorGalleryUrls(vendor, maxCount = 6) {
  const businessName = String(vendor?.businessName || "event-vendor");
  const desiredCount = 3 + (hashCode(`${businessName}-gallery-count`) % 4);
  const count = Math.max(3, Math.min(maxCount, desiredCount));
  return portfolioPoolForVendor(vendor).slice(0, count);
}

